"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

L = 6
RA = 170
RB = 410
P1 = 100
q1 = 120
q2 = 120

x = np.linspace(0, L, 500)
v = np.zeros_like(x)

for i in range(len(x)):
  if x[i] < 2:
    v[i] = RA - (q1 * x[i])
  elif x[i] < 4:
    v[i] = RA - (q1 * 2) - P1
  else:
    v[i] = RA - (q1 * 2) - P1 + RB - (q2 * (x[i] - 4))

# AI helped me with 'tab:blue' to get the line to show up
plt.plot(x, v, color = 'tab:blue', alpha = 0.8)
plt.xlabel('x (ft)')
plt.ylabel('v (lb)')
plt.title('Shear Diagram')
plt.fill_between(x, v, color = 'lightblue')
# AI helped me to get the x axis line to show up
plt.axhline(0, color = 'black', linewidth=0.8)
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

L = 6
RA = 170
RB = 410
P1 = 100
q1 = 120
q2 = 120

x = np.linspace(0, L, 500)
M = np.zeros_like(x)

for i in range(len(x)):
    if x[i] < 2:
        M[i] = (RA * x[i]) - (q1 * (x[i] ** 2) / 2)

    elif x[i] < 4:
        M[i] = (RA * x[i]) - (q1 * 2 * (x[i] - 1)) - (P1 * (x[i] - 2))

    else:
        M[i] = (
            (RA * x[i])
            - (q1 * 2 * (x[i] - 1))
            - (P1 * (x[i] - 2))
            + (RB * (x[i] - 4))
            - (q2 * ((x[i] - 4) * ((x[i] - 4) / 2))))

plt.plot(x, M, color='tab:blue', alpha=0.8)
plt.fill_between(x, M, color='lightblue')

plt.xlabel('x (ft)')
plt.ylabel('M (lb-ft)')
plt.title('Moment Diagram')

plt.axhline(0, color='black', linewidth=0.8)

plt.show()

